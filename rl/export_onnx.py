"""Export a trained SB3 policy to ONNX and a small C header.

The network is the deterministic action mean: MLP 50-64-64-12.
Firmware on a Raspberry Pi can run the ONNX file. An ESP32 can run the header.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import torch
from torch import nn

from rl import spec


class _Actor(nn.Module):
    def __init__(self, policy):
        super().__init__()
        self.latent = policy.mlp_extractor.policy_net
        self.action = policy.action_net

    def forward(self, obs: torch.Tensor) -> torch.Tensor:
        return self.action(self.latent(obs))


def _layers(policy) -> list[tuple]:
    layers = []
    for module in policy.mlp_extractor.policy_net:
        if isinstance(module, nn.Linear):
            layers.append(("linear", module.weight.detach().cpu().numpy(), module.bias.detach().cpu().numpy()))
        elif isinstance(module, nn.Tanh):
            layers.append(("tanh",))
        elif isinstance(module, nn.ReLU):
            layers.append(("relu",))
        else:
            raise TypeError(f"unsupported policy module {type(module).__name__}")
    action = policy.action_net
    layers.append(("linear", action.weight.detach().cpu().numpy(), action.bias.detach().cpu().numpy()))
    return layers


def _fmt(values: np.ndarray) -> str:
    flat = np.asarray(values, dtype=np.float32).reshape(-1)
    return ", ".join(f"{v:.8e}f" for v in flat)


def write_header(skill: str, layers: list[tuple], path: Path) -> None:
    name = spec.c_symbol(skill)
    lines = [
        "#pragma once",
        "/* Generated by python -m rl export. Deterministic PPO action mean. */",
        "#include <math.h>",
        f"#define MINI_DOG_{name.upper()}_OBS {spec.OBS_DIM}",
        f"#define MINI_DOG_{name.upper()}_ACT {spec.N_JOINTS}",
        "static inline void mini_dog_linear(const float* x, const float* w, const float* b, int in_dim, int out_dim, float* y) {",
        "  for (int i = 0; i < out_dim; ++i) {",
        "    float sum = b[i];",
        "    const float* row = w + (size_t)i * (size_t)in_dim;",
        "    for (int j = 0; j < in_dim; ++j) sum += row[j] * x[j];",
        "    y[i] = sum;",
        "  }",
        "}",
    ]
    # The helper uses size_t. Include stddef.
    lines.insert(3, "#include <stddef.h>")
    buffers = []
    idx = 0
    for layer in layers:
        if layer[0] != "linear":
            continue
        weight, bias = layer[1], layer[2]
        lines.append(f"static const float {name}_w{idx}[{weight.size}] = {{{_fmt(weight)}}};")
        lines.append(f"static const float {name}_b{idx}[{bias.size}] = {{{_fmt(bias)}}};")
        buffers.append((weight.shape[1], weight.shape[0], idx))
        idx += 1
    lines.append(f"static inline void policy_{name}(const float* obs, float* action) {{")
    # Allocate the larger hidden width.
    hidden = max(out for _in, out, _i in buffers[:-1]) if len(buffers) > 1 else spec.N_JOINTS
    lines.append(f"  float h0[{hidden}];")
    lines.append(f"  float h1[{hidden}];")
    cursor_in = "obs"
    cursor_out = "h0"
    linear_i = 0
    for li, layer in enumerate(layers):
        kind = layer[0]
        last = li == len(layers) - 1
        if kind == "linear":
            in_dim, out_dim, index = buffers[linear_i]
            dest = "action" if last else cursor_out
            lines.append(
                f"  mini_dog_linear({cursor_in}, {name}_w{index}, {name}_b{index}, {in_dim}, {out_dim}, {dest});"
            )
            linear_i += 1
            if not last:
                cursor_in, cursor_out = cursor_out, ("h1" if cursor_out == "h0" else "h0")
        elif kind == "tanh":
            # activation applies to the buffer just written, which is the new cursor_in
            lines.append(f"  for (int i = 0; i < {hidden}; ++i) {cursor_in}[i] = tanhf({cursor_in}[i]);")
        elif kind == "relu":
            lines.append(f"  for (int i = 0; i < {hidden}; ++i) if ({cursor_in}[i] < 0.f) {cursor_in}[i] = 0.f;")
    lines.append("}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def _numpy_forward(obs: np.ndarray, layers: list[tuple]) -> np.ndarray:
    x = obs.astype(np.float32)
    for layer in layers:
        if layer[0] == "linear":
            weight, bias = layer[1], layer[2]
            x = x @ weight.T + bias
        elif layer[0] == "tanh":
            x = np.tanh(x)
        elif layer[0] == "relu":
            x = np.maximum(x, 0)
    return x.astype(np.float32)


def export_checkpoint(checkpoint: Path, skill: str, onnx_path: Path | None = None) -> dict:
    from stable_baselines3 import PPO

    checkpoint = Path(checkpoint)
    onnx_path = Path(onnx_path or (spec.ROOT / spec.policy_filename(skill)))
    model = PPO.load(str(checkpoint), device="cpu")
    actor = _Actor(model.policy).eval()
    dummy = torch.zeros(1, spec.OBS_DIM, dtype=torch.float32)
    onnx_path.parent.mkdir(parents=True, exist_ok=True)
    export_kwargs = dict(
        input_names=["obs"],
        output_names=["action"],
        opset_version=17,
        dynamic_axes={"obs": {0: "batch"}, "action": {0: "batch"}},
    )
    try:
        torch.onnx.export(actor, dummy, str(onnx_path), dynamo=False, **export_kwargs)
    except TypeError:
        torch.onnx.export(actor, dummy, str(onnx_path), **export_kwargs)
    layers = _layers(model.policy)
    header = spec.FIRMWARE / "include" / f"{spec.c_symbol(skill)}_policy.h"
    write_header(skill, layers, header)

    rng = np.random.default_rng(0)
    sample = rng.normal(size=(4, spec.OBS_DIM)).astype(np.float32)
    with torch.no_grad():
        torch_out = actor(torch.from_numpy(sample)).numpy()
    numpy_out = np.stack([_numpy_forward(row, layers) for row in sample])
    if not np.allclose(torch_out, numpy_out, atol=1e-5):
        raise RuntimeError(f"numpy policy mismatch for {skill}")
    import onnxruntime as ort

    session = ort.InferenceSession(str(onnx_path), providers=["CPUExecutionProvider"])
    onnx_out = session.run(None, {"obs": sample})[0]
    if not np.allclose(torch_out, onnx_out, atol=1e-4):
        raise RuntimeError(f"onnx policy mismatch for {skill}")
    c_ok = _verify_c(skill, header, sample, torch_out)

    def _rel(path: Path) -> str:
        try:
            return str(path.relative_to(spec.ROOT))
        except ValueError:
            return str(path)

    return {
        "onnx": _rel(onnx_path),
        "header": _rel(header),
        "checked": True,
        "c_header_checked": c_ok,
    }


def _verify_c(skill: str, header: Path, sample: np.ndarray, expected: np.ndarray) -> bool:
    """Compile the generated header and compare one batch. Skip if gcc is missing."""
    import shutil
    import subprocess
    import tempfile

    if shutil.which("gcc") is None:
        return False
    name = spec.c_symbol(skill)
    rows = []
    for row in sample:
        literal = ", ".join(f"{v:.8e}f" for v in row)
        rows.append(f"    {{ {literal} }},")
    source = f"""
#include <stdio.h>
#include "{header.resolve()}"
int main(void) {{
    const float obs[{sample.shape[0]}][{spec.OBS_DIM}] = {{
{chr(10).join(rows)}
    }};
    for (int n = 0; n < {sample.shape[0]}; ++n) {{
        float action[{spec.N_JOINTS}];
        policy_{name}(obs[n], action);
        for (int i = 0; i < {spec.N_JOINTS}; ++i) printf("%.8e\\n", action[i]);
    }}
    return 0;
}}
"""
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "check.c"
        bin_path = Path(tmp) / "check"
        src.write_text(source)
        compiled = subprocess.run(
            ["gcc", "-O2", "-std=c11", str(src), "-lm", "-o", str(bin_path)],
            capture_output=True,
            text=True,
        )
        if compiled.returncode != 0:
            raise RuntimeError(f"C header failed to compile: {compiled.stderr[-500:]}")
        ran = subprocess.run([str(bin_path)], capture_output=True, text=True, check=True)
    values = np.array([float(line) for line in ran.stdout.split() if line.strip()], dtype=np.float32)
    got = values.reshape(sample.shape[0], spec.N_JOINTS)
    if not np.allclose(got, expected, atol=1e-4):
        raise RuntimeError(f"C policy mismatch for {skill}: max abs {np.max(np.abs(got - expected))}")
    return True
